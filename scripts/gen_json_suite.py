"""Generate the JSONTestSuite cases that the integration suite reads.

JSONTestSuite is a corpus of documents that a reader must accept, must refuse,
or may answer either way. The files are bytes rather than text on purpose: some
of them are not valid UTF-8, and a reader that decodes before it looks would
accept a UTF-16 document that merely looks like JSON.

The corpus is not in this repository and is not downloaded by CI, so this script
is run by hand against a local clone and its output is committed. Bump CORPUS
when the clone moves to a later commit, and rerun.

    python scripts/gen_json_suite.py --corpus ../JSONTestSuite

The verdict of a file whose name starts with `i_` is the reader's to choose. The
choices this library makes are stated in `POLICY` below and in the README: a
number too large for a double is accepted because the digits are kept as they
were written, a byte order mark is skipped, and three things are refused: half a
surrogate pair, a truncated sequence or bytes that are not UTF-8, and a document
nested deeper than the reader's limit — which is why the five hundred level file
is refused here.
"""

import argparse
import pathlib

CORPUS = "1ef36fa01286573e846ac449e8683f8833c5b26a"
CHUNK = 40_000

# Files the suite leaves open, and what this reader does with them.
POLICY = {
    "i_number_double_huge_neg_exp": True,
    "i_number_huge_exp": True,
    "i_number_neg_int_huge_exp": True,
    "i_number_pos_double_huge_exp": True,
    "i_number_real_neg_overflow": True,
    "i_number_real_pos_overflow": True,
    "i_number_real_underflow": True,
    "i_number_too_big_neg_int": True,
    "i_number_too_big_pos_int": True,
    "i_number_very_big_negative_int": True,
    "i_object_key_lone_2nd_surrogate": False,
    "i_string_1st_surrogate_but_2nd_missing": False,
    "i_string_1st_valid_surrogate_2nd_invalid": False,
    "i_string_incomplete_surrogate_and_escape_valid": False,
    "i_string_incomplete_surrogate_pair": False,
    "i_string_incomplete_surrogates_escape_valid": False,
    "i_string_invalid_lonely_surrogate": False,
    "i_string_invalid_surrogate": False,
    "i_string_invalid_utf-8": False,
    "i_string_UTF-8_invalid_sequence": False,
    "i_string_UTF8_surrogate_U+D800": False,
    "i_string_inverted_surrogates_U+1D11E": False,
    "i_string_iso_latin_1": False,
    "i_string_lone_second_surrogate": False,
    "i_string_lone_utf8_continuation_byte": False,
    "i_string_not_in_unicode_range": False,
    "i_string_overlong_sequence_2_bytes": False,
    "i_string_overlong_sequence_6_bytes": False,
    "i_string_overlong_sequence_6_bytes_null": False,
    "i_string_truncated-utf-8": False,
    "i_string_UTF-16LE_with_BOM": False,
    "i_string_utf16BE_no_BOM": False,
    "i_string_utf16LE_no_BOM": False,
    "i_structure_500_nested_arrays": False,
    "i_structure_UTF-8_BOM_empty_object": True,
}


def verdict(name, group):
    if group == "y":
        return True
    if group == "n":
        return False
    if name not in POLICY:
        raise SystemExit(f"{name}: a file the suite leaves open has no decision in POLICY")
    return POLICY[name]


def entry(name, data, accept):
    """One case, as the lines that put it in the table.

    A file of a hundred thousand brackets is two hundred thousand characters of
    hexadecimal, and a source line that long is past what the compiler reads in
    one line, so a long one is written as several literals joined by `+`, one to
    a line.
    """
    hexed = data.hex()
    verdict = "true" if accept else "false"
    if len(hexed) <= 30_000:
        return [f'    ("{name}", "{hexed}", {verdict}),']
    pieces = [hexed[index : index + 30_000] for index in range(0, len(hexed), 30_000)]
    lines = ["    (", f'      "{name}",']
    for index, piece in enumerate(pieces):
        lines.append(f'      "{piece}"' + (" +" if index < len(pieces) - 1 else ","))
    lines.append(f"      {verdict},")
    lines.append("    ),")
    return lines


def render(entries):
    out = [
        "// Copyright 2026 Leo Cheng",
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "///|",
        "/// JSONTestSuite, as bytes: every file of `test_parsing` with the verdict",
        "/// this reader has to reach on it.",
        "///",
        f"/// Generated by `scripts/gen_json_suite.py` from commit {CORPUS},",
        "/// which is where the corpus is; it is not in this repository. Each entry",
        "/// is the name of the file, its bytes in hexadecimal, and whether the",
        "/// reader has to accept it. A file whose name starts with `i_` is one the",
        "/// suite leaves open, and the answer here is the choice this reader makes.",
    ]
    blocks = []
    current = []
    size = 0
    for name, data, accept in entries:
        lines = entry(name, data, accept)
        weight = sum(len(line) for line in lines)
        if size + weight > CHUNK and current:
            blocks.append(current)
            current = []
            size = 0
        current.extend(lines)
        size += weight
    if current:
        blocks.append(current)
    for index, block in enumerate(blocks):
        out.append("")
        out.append("///|")
        out.append(f"fn block_{index}() -> Array[(String, String, Bool)] {{")
        out.append("  [")
        out.extend(block)
        out.append("  ]")
        out.append("}")
    out.append("")
    out.append("///|")
    out.append("/// Every case of the corpus, in the order the files are named.")
    out.append("fn cases() -> Array[(String, String, Bool)] {")
    out.append("  let all = Array(capacity=318)")
    for index in range(len(blocks)):
        out.append(f"  all.append(block_{index}()[:])")
    out.append("  all")
    out.append("}")
    out.append("")
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--corpus", required=True, help="path to a JSONTestSuite clone")
    parser.add_argument("--out", default="integration/json-suite/suite/cases.mbt")
    args = parser.parse_args()
    root = pathlib.Path(args.corpus) / "test_parsing"
    entries = []
    for path in sorted(root.glob("*.json")):
        name = path.stem
        group = name.split("_", 1)[0]
        entries.append((name, path.read_bytes(), verdict(name, group)))
    text = render(entries)
    out = pathlib.Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8", newline="\n")
    accepted = sum(1 for _, _, accept in entries if accept)
    print(f"{len(entries)} cases, {accepted} accepted, {len(entries) - accepted} refused -> {out}")


if __name__ == "__main__":
    main()
